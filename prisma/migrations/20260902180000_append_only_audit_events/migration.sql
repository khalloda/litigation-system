CREATE FUNCTION public.audit_bound_json_value(
    p_value jsonb,
    p_max_characters integer,
    p_capture_mode text
)
RETURNS jsonb
LANGUAGE plpgsql
IMMUTABLE
PARALLEL SAFE
SET search_path = pg_catalog, public, pg_temp
AS $BOUND_VALUE$
DECLARE
    text_value text;
BEGIN
    IF p_capture_mode='redacted' THEN
        RETURN jsonb_build_object('$redacted',true,'$reason','sensitive_field');
    END IF;
    IF p_capture_mode<>'value' THEN
        RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Unknown audit capture mode';
    END IF;
    IF p_value IS NULL OR jsonb_typeof(p_value)='null' THEN
        RETURN 'null'::jsonb;
    END IF;
    IF jsonb_typeof(p_value) IN ('object','array') THEN
        RETURN jsonb_build_object('$redacted',true,'$reason','structured_value');
    END IF;
    IF jsonb_typeof(p_value)<>'string' THEN
        RETURN p_value;
    END IF;
    text_value := p_value #>> '{}';
    IF public.audit_contains_secret_pattern(text_value) THEN
        RETURN jsonb_build_object('$redacted',true,'$reason','secret_pattern');
    END IF;
    IF char_length(text_value)>p_max_characters THEN
        RETURN jsonb_build_object(
            '$value',left(text_value,p_max_characters),
            '$truncated',true,
            '$original_characters',char_length(text_value)
        );
    END IF;
    RETURN p_value;
END;
$BOUND_VALUE$;

CREATE FUNCTION public.audit_safe_flat_object(p_value jsonb)
RETURNS boolean
LANGUAGE plpgsql
IMMUTABLE
PARALLEL SAFE
SET search_path = pg_catalog, public, pg_temp
AS $SAFE_OBJECT$
DECLARE
    item record;
    item_count integer := 0;
    text_value text;
BEGIN
    IF p_value IS NULL OR jsonb_typeof(p_value)<>'object' OR octet_length(p_value::text)>16384 THEN
        RETURN false;
    END IF;
    FOR item IN SELECT key,value FROM jsonb_each(p_value) LOOP
        item_count := item_count+1;
        IF item_count>32
           OR item.key !~ '^[a-z][a-z0-9_]{0,63}$'
           OR item.key ~* '(password|token|cookie|secret|credential|authorization|private_key|api_key|database_url|connection_string|payload|binary|content)' THEN
            RETURN false;
        END IF;
        IF jsonb_typeof(item.value) NOT IN ('string','number','boolean','null') THEN
            RETURN false;
        END IF;
        IF jsonb_typeof(item.value)='string' THEN
            text_value := item.value #>> '{}';
            IF char_length(text_value)>256 OR public.audit_contains_secret_pattern(text_value) THEN
                RETURN false;
            END IF;
        END IF;
    END LOOP;
    RETURN true;
END;
$SAFE_OBJECT$;

CREATE FUNCTION public.audit_set_event_context(
    p_request_id uuid,
    p_correlation_id uuid,
    p_audit_session_id uuid,
    p_ip_address inet,
    p_user_agent text,
    p_device_class text
)
RETURNS void
LANGUAGE plpgsql
VOLATILE
CALLED ON NULL INPUT
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $SET_CONTEXT$
DECLARE
    safe_agent text;
    agent_truncated boolean;
BEGIN
    IF p_request_id IS NULL OR p_correlation_id IS NULL OR p_audit_session_id IS NULL
       OR p_request_id='00000000-0000-0000-0000-000000000000'::uuid
       OR p_correlation_id='00000000-0000-0000-0000-000000000000'::uuid
       OR p_audit_session_id='00000000-0000-0000-0000-000000000000'::uuid
       OR p_device_class NOT IN ('system','desktop','mobile','tablet','bot','unknown') THEN
        RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Invalid server audit event context';
    END IF;
    agent_truncated := p_user_agent IS NOT NULL AND char_length(p_user_agent)>512;
    safe_agent := CASE
        WHEN p_user_agent IS NULL OR p_user_agent='' THEN ''
        WHEN public.audit_contains_secret_pattern(p_user_agent) THEN '[redacted]'
        ELSE left(p_user_agent,512)
    END;
    IF safe_agent='[redacted]' THEN agent_truncated := true; END IF;
    PERFORM set_config('litigation.audit_request_id',p_request_id::text,true);
    PERFORM set_config('litigation.audit_correlation_id',p_correlation_id::text,true);
    PERFORM set_config('litigation.audit_session_id',p_audit_session_id::text,true);
    PERFORM set_config('litigation.audit_ip_address',coalesce(p_ip_address::text,''),true);
    PERFORM set_config('litigation.audit_user_agent',safe_agent,true);
    PERFORM set_config('litigation.audit_user_agent_truncated',agent_truncated::text,true);
    PERFORM set_config('litigation.audit_device_class',p_device_class,true);
END;
$SET_CONTEXT$;

CREATE FUNCTION public.audit_ensure_event_context()
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $ENSURE_CONTEXT$
DECLARE
    request_value text := current_setting('litigation.audit_request_id',true);
    correlation_value text := current_setting('litigation.audit_correlation_id',true);
    session_value text := current_setting('litigation.audit_session_id',true);
    ip_value text := current_setting('litigation.audit_ip_address',true);
    agent_value text := current_setting('litigation.audit_user_agent',true);
    truncated_value text := current_setting('litigation.audit_user_agent_truncated',true);
    device_value text := current_setting('litigation.audit_device_class',true);
BEGIN
    IF coalesce(request_value,'')='' THEN
        IF coalesce(correlation_value,'')<>'' OR coalesce(session_value,'')<>'' THEN
            RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Partial audit event context is refused';
        END IF;
        request_value := gen_random_uuid()::text;
        correlation_value := gen_random_uuid()::text;
        session_value := gen_random_uuid()::text;
        ip_value := '';
        agent_value := '';
        truncated_value := 'false';
        device_value := CASE WHEN public.audit_current_actor_id()=1 THEN 'system' ELSE 'unknown' END;
        PERFORM set_config('litigation.audit_request_id',request_value,true);
        PERFORM set_config('litigation.audit_correlation_id',correlation_value,true);
        PERFORM set_config('litigation.audit_session_id',session_value,true);
        PERFORM set_config('litigation.audit_ip_address','',true);
        PERFORM set_config('litigation.audit_user_agent','',true);
        PERFORM set_config('litigation.audit_user_agent_truncated','false',true);
        PERFORM set_config('litigation.audit_device_class',device_value,true);
    END IF;
    BEGIN
        PERFORM request_value::uuid,correlation_value::uuid,session_value::uuid;
        IF coalesce(ip_value,'')<>'' THEN PERFORM ip_value::inet; END IF;
        IF coalesce(truncated_value,'') NOT IN ('true','false')
           OR coalesce(device_value,'') NOT IN ('system','desktop','mobile','tablet','bot','unknown')
           OR char_length(coalesce(agent_value,''))>512 THEN
            RAISE invalid_parameter_value;
        END IF;
    EXCEPTION WHEN OTHERS THEN
        RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Invalid transaction-local audit event context';
    END;
    RETURN jsonb_build_object(
        'request_id',request_value,
        'correlation_id',correlation_value,
        'audit_session_id',session_value,
        'ip_address',nullif(ip_value,''),
        'user_agent',nullif(agent_value,''),
        'user_agent_truncated',truncated_value::boolean,
        'device_class',device_value
    );
END;
$ENSURE_CONTEXT$;

CREATE FUNCTION public.audit_write_event(
    p_action text,
    p_outcome text,
    p_entity_schema text,
    p_entity_table text,
    p_entity_key jsonb,
    p_changed_fields text[],
    p_before_values jsonb,
    p_after_values jsonb,
    p_target_actor_id integer,
    p_attempted_username text,
    p_resource_identifier text,
    p_parameters jsonb,
    p_reason_code text,
    p_event_metadata jsonb
)
RETURNS bigint
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $WRITE_EVENT$
DECLARE
    current_actor_id integer := public.audit_current_actor_id();
    context_value jsonb := public.audit_ensure_event_context();
    actor_row record;
    target_actor_key text;
    target_username text;
    target_display_name text;
    target_role text;
    safe_attempt text;
    safe_attempt_truncated boolean := false;
    new_event_id bigint;
BEGIN
    SELECT a.actor_key,a.actor_kind,u.username,p.name_ar,u.role_code,a.identity_label
      INTO STRICT actor_row
      FROM public.audit_actors a
      LEFT JOIN public.user_accounts u ON u.id=a.user_account_id
      LEFT JOIN public.people p ON p.id=u.person_id
     WHERE a.id=current_actor_id;
    IF p_target_actor_id IS NOT NULL THEN
        SELECT a.actor_key,u.username,coalesce(p.name_ar,a.identity_label),u.role_code
          INTO STRICT target_actor_key,target_username,target_display_name,target_role
          FROM public.audit_actors a
          LEFT JOIN public.user_accounts u ON u.id=a.user_account_id
          LEFT JOIN public.people p ON p.id=u.person_id
         WHERE a.id=p_target_actor_id;
    END IF;
    IF p_attempted_username IS NOT NULL AND p_attempted_username<>'' THEN
        safe_attempt_truncated := char_length(p_attempted_username)>64;
        safe_attempt := CASE
            WHEN public.audit_contains_secret_pattern(p_attempted_username) THEN '[redacted]'
            ELSE left(p_attempted_username,64)
        END;
        IF safe_attempt='[redacted]' THEN safe_attempt_truncated := true; END IF;
    END IF;
    INSERT INTO public.audit_events(
        actor_id,actor_key_snapshot,actor_username_snapshot,
        actor_display_name_snapshot,actor_role_snapshot,
        target_actor_id,target_actor_key_snapshot,target_username_snapshot,
        target_display_name_snapshot,target_role_snapshot,
        action,outcome,entity_schema,entity_table,entity_key,changed_fields,
        before_values,after_values,request_id,correlation_id,audit_session_id,
        ip_address,user_agent,user_agent_truncated,device_class,
        attempted_username,attempted_username_truncated,resource_identifier,
        reason_code,parameters,event_metadata
    ) VALUES (
        current_actor_id,actor_row.actor_key,actor_row.username,
        coalesce(actor_row.name_ar,actor_row.identity_label),actor_row.role_code,
        p_target_actor_id,target_actor_key,target_username,target_display_name,target_role,
        p_action,p_outcome,p_entity_schema,p_entity_table,p_entity_key,
        coalesce(p_changed_fields,ARRAY[]::text[]),
        coalesce(p_before_values,'{}'::jsonb),coalesce(p_after_values,'{}'::jsonb),
        (context_value->>'request_id')::uuid,
        (context_value->>'correlation_id')::uuid,
        (context_value->>'audit_session_id')::uuid,
        nullif(context_value->>'ip_address','')::inet,
        nullif(context_value->>'user_agent',''),
        (context_value->>'user_agent_truncated')::boolean,
        context_value->>'device_class',safe_attempt,safe_attempt_truncated,
        nullif(left(coalesce(p_resource_identifier,''),256),''),
        p_reason_code,coalesce(p_parameters,'{}'::jsonb),coalesce(p_event_metadata,'{}'::jsonb)
    ) RETURNING id INTO new_event_id;
    RETURN new_event_id;
END;
$WRITE_EVENT$;

CREATE FUNCTION public.audit_append_semantic_event(
    p_action text,
    p_outcome text,
    p_entity_schema text,
    p_entity_table text,
    p_entity_key jsonb,
    p_target_actor_id integer,
    p_attempted_username text,
    p_resource_identifier text,
    p_parameters jsonb,
    p_reason_code text,
    p_event_metadata jsonb
)
RETURNS bigint
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $SEMANTIC_EVENT$
DECLARE
    current_actor_id integer := public.audit_current_actor_id();
    current_kind text;
    current_key text;
    current_user_account_id integer;
    target_kind text;
    target_user_account_id integer;
BEGIN
    SELECT actor_kind,actor_key,user_account_id
      INTO STRICT current_kind,current_key,current_user_account_id
      FROM public.audit_actors WHERE id=current_actor_id;
    IF p_target_actor_id IS NOT NULL THEN
        SELECT actor_kind,user_account_id INTO STRICT target_kind,target_user_account_id
          FROM public.audit_actors WHERE id=p_target_actor_id;
        IF target_kind<>'human' OR target_user_account_id IS NULL THEN
            RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Semantic target must be a human account actor';
        END IF;
    END IF;
    IF p_action NOT IN (
        'login_succeeded','login_failed','account_locked',
        'password_changed','password_initialized','password_reset',
        'archive','restore','account_created','account_enabled','account_disabled',
        'role_changed','report_executed','export_completed','download_completed'
    ) THEN
        RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Unsupported semantic audit action';
    END IF;
    IF p_outcome NOT IN ('succeeded','failed','blocked')
       OR NOT public.audit_safe_flat_object(coalesce(p_parameters,'{}'::jsonb))
       OR NOT public.audit_safe_flat_object(coalesce(p_event_metadata,'{}'::jsonb))
       OR (p_reason_code IS NOT NULL AND p_reason_code !~ '^[a-z][a-z0-9_]{0,63}$') THEN
        RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Unsafe semantic audit payload';
    END IF;
    IF p_resource_identifier IS NOT NULL AND (
        p_resource_identifier='' OR char_length(p_resource_identifier)>256
        OR public.audit_contains_secret_pattern(p_resource_identifier)
    ) THEN
        RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Unsafe semantic resource identifier';
    END IF;
    IF (p_entity_schema IS NULL) IS DISTINCT FROM (p_entity_table IS NULL)
       OR (p_entity_schema IS NULL) IS DISTINCT FROM (p_entity_key IS NULL)
       OR (p_entity_key IS NOT NULL AND
           (p_entity_schema<>'public'
            OR NOT EXISTS (
                SELECT 1 FROM public.audit_event_table_rules r
                 WHERE r.entity_schema=p_entity_schema AND r.entity_table=p_entity_table
            )
            OR NOT public.audit_safe_flat_object(p_entity_key)
            OR octet_length(p_entity_key::text)>2048)) THEN
        RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Invalid semantic audit entity';
    END IF;
    IF p_action='login_succeeded' THEN
        IF current_kind<>'human' OR p_outcome<>'succeeded'
           OR p_target_actor_id IS NOT NULL OR p_attempted_username IS NOT NULL
           OR p_entity_table<>'user_accounts'
           OR p_entity_key IS DISTINCT FROM jsonb_build_object('id',current_user_account_id) THEN
            RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Login-success actor or shape is invalid';
        END IF;
    ELSIF p_action='login_failed' THEN
        IF current_key<>'system_authentication' OR p_outcome NOT IN ('failed','blocked')
           OR coalesce(p_attempted_username,'')=''
           OR (p_target_actor_id IS NULL AND p_entity_key IS NOT NULL)
           OR (p_target_actor_id IS NOT NULL AND (
               p_entity_table<>'user_accounts'
               OR p_entity_key IS DISTINCT FROM jsonb_build_object('id',target_user_account_id)
           )) THEN
            RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Login-failure actor or shape is invalid';
        END IF;
    ELSIF p_action='account_locked' THEN
        IF current_key<>'system_authentication' OR p_outcome<>'succeeded'
           OR p_target_actor_id IS NULL OR p_entity_table<>'user_accounts'
           OR p_entity_key IS DISTINCT FROM jsonb_build_object('id',target_user_account_id) THEN
            RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Lockout actor or shape is invalid';
        END IF;
    ELSIF p_action='password_changed' THEN
        IF current_kind<>'human' OR p_outcome<>'succeeded'
           OR p_target_actor_id IS DISTINCT FROM current_actor_id
           OR p_entity_table<>'user_accounts'
           OR p_entity_key IS DISTINCT FROM jsonb_build_object('id',current_user_account_id) THEN
            RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Self-password actor or shape is invalid';
        END IF;
    ELSIF p_action IN ('password_initialized','password_reset') THEN
        IF current_key<>'system_administration' OR p_outcome<>'succeeded'
           OR p_target_actor_id IS NULL OR p_entity_table<>'user_accounts'
           OR p_entity_key IS DISTINCT FROM jsonb_build_object('id',target_user_account_id) THEN
            RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Administrative password actor or shape is invalid';
        END IF;
    ELSIF p_action IN ('archive','restore','account_created','account_enabled','account_disabled','role_changed') THEN
        IF current_kind<>'human' OR p_outcome<>'succeeded' OR p_entity_key IS NULL THEN
            RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Lifecycle actor or shape is invalid';
        END IF;
    ELSIF p_action IN ('report_executed','export_completed','download_completed') THEN
        IF current_kind<>'human' OR coalesce(p_resource_identifier,'')='' THEN
            RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Report/export/download actor or shape is invalid';
        END IF;
    END IF;
    RETURN public.audit_write_event(
        p_action,p_outcome,p_entity_schema,p_entity_table,p_entity_key,
        ARRAY[]::text[],'{}'::jsonb,'{}'::jsonb,p_target_actor_id,
        p_attempted_username,p_resource_identifier,p_parameters,p_reason_code,p_event_metadata
    );
END;
$SEMANTIC_EVENT$;

CREATE FUNCTION public.audit_capture_row_event()
RETURNS trigger
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $ROW_EVENT$
DECLARE
    table_rule public.audit_event_table_rules%ROWTYPE;
    old_value jsonb;
    new_value jsonb;
    key_source jsonb;
    entity_key jsonb;
    fields text[];
    before_payload jsonb := '{}'::jsonb;
    after_payload jsonb := '{}'::jsonb;
    action_name text;
BEGIN
    SELECT * INTO STRICT table_rule
      FROM public.audit_event_table_rules
     WHERE entity_schema=TG_TABLE_SCHEMA AND entity_table=TG_TABLE_NAME;
    old_value := CASE WHEN TG_OP='INSERT' THEN NULL ELSE to_jsonb(OLD) END;
    new_value := CASE WHEN TG_OP='DELETE' THEN NULL ELSE to_jsonb(NEW) END;
    key_source := coalesce(new_value,old_value);
    SELECT jsonb_object_agg(key_name,key_source->key_name ORDER BY ordinal)
      INTO entity_key
      FROM unnest(table_rule.key_fields) WITH ORDINALITY AS keys(key_name,ordinal);

    IF TG_OP='INSERT' THEN
        SELECT array_agg(f.field_name ORDER BY f.field_name),
               jsonb_object_agg(
                   f.field_name,
                    public.audit_bound_json_value(
                        new_value->f.field_name,f.max_text_characters,f.capture_mode)
                   ORDER BY f.field_name)
          INTO fields,after_payload
          FROM public.audit_event_fields f
         WHERE f.entity_schema=TG_TABLE_SCHEMA AND f.entity_table=TG_TABLE_NAME;
        action_name := CASE WHEN table_rule.entity_kind='relationship'
                            THEN 'relationship_added' ELSE 'record_created' END;
    ELSIF TG_OP='UPDATE' THEN
        SELECT array_agg(f.field_name ORDER BY f.field_name),
               coalesce(jsonb_object_agg(
                   f.field_name,
                    public.audit_bound_json_value(
                        old_value->f.field_name,f.max_text_characters,f.capture_mode)
                   ORDER BY f.field_name),'{}'::jsonb),
               coalesce(jsonb_object_agg(
                   f.field_name,
                    public.audit_bound_json_value(
                        new_value->f.field_name,f.max_text_characters,f.capture_mode)
                   ORDER BY f.field_name),'{}'::jsonb)
          INTO fields,before_payload,after_payload
          FROM public.audit_event_fields f
         WHERE f.entity_schema=TG_TABLE_SCHEMA AND f.entity_table=TG_TABLE_NAME
           AND (old_value->f.field_name) IS DISTINCT FROM (new_value->f.field_name);
        IF fields IS NULL OR cardinality(fields)=0 THEN RETURN NEW; END IF;
        action_name := CASE WHEN table_rule.entity_kind='relationship'
                            THEN 'relationship_updated' ELSE 'record_updated' END;
    ELSE
        IF table_rule.entity_kind<>'relationship' THEN
            RAISE EXCEPTION 'Physical record deletion is outside the Task 3.3B/D25 contract';
        END IF;
        SELECT array_agg(f.field_name ORDER BY f.field_name),
               jsonb_object_agg(
                   f.field_name,
                    public.audit_bound_json_value(
                        old_value->f.field_name,f.max_text_characters,f.capture_mode)
                   ORDER BY f.field_name)
          INTO fields,before_payload
          FROM public.audit_event_fields f
         WHERE f.entity_schema=TG_TABLE_SCHEMA AND f.entity_table=TG_TABLE_NAME;
        action_name := 'relationship_removed';
    END IF;
    PERFORM public.audit_write_event(
        action_name,'succeeded',TG_TABLE_SCHEMA,TG_TABLE_NAME,entity_key,
        fields,before_payload,after_payload,NULL,NULL,NULL,'{}'::jsonb,NULL,'{}'::jsonb
    );
    RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END;
$ROW_EVENT$;

