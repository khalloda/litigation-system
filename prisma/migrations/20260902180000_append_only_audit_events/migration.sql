        GROUP BY r.entity_schema,r.entity_table HAVING count(f.field_name)=0
    ) THEN
        RAISE EXCEPTION 'Task 3.3B explicit field allowlist is unsafe or incomplete';
    END IF;
    SELECT count(*) INTO trigger_count
      FROM pg_trigger t JOIN pg_class c ON c.oid=t.tgrelid
      JOIN pg_namespace n ON n.oid=c.relnamespace
     WHERE n.nspname='public' AND t.tgname='audit_event_capture'
       AND NOT t.tgisinternal AND t.tgenabled='O';
    IF trigger_count<>38 THEN
        RAISE EXCEPTION 'Task 3.3B expected 38 enabled row-event triggers, found %',trigger_count;
    END IF;
    IF (SELECT count(*) FROM public.audit_events)<>1
       OR (SELECT count(*) FROM public.audit_events WHERE action='audit_baseline_established')<>1
       OR (SELECT count(*) FROM public.audit_event_checkpoints)<>1 THEN
        RAISE EXCEPTION 'Task 3.3B must establish exactly one aggregate baseline event/checkpoint';
    END IF;
    IF has_table_privilege('litigation_runtime','public.audit_events','SELECT')
       OR has_table_privilege('litigation_runtime','public.audit_events','INSERT')
       OR has_table_privilege('litigation_runtime','public.audit_events','UPDATE')
       OR has_table_privilege('litigation_runtime','public.audit_events','DELETE')
       OR has_table_privilege('litigation_runtime','public.audit_events','TRUNCATE')
       OR has_table_privilege('litigation_runtime','public.audit_events','TRIGGER')
       OR NOT has_function_privilege('litigation_runtime',
          'public.audit_set_event_context(uuid,uuid,uuid,inet,text,text)','EXECUTE')
       OR NOT has_function_privilege('litigation_runtime',
          'public.audit_append_semantic_event(text,text,text,text,jsonb,integer,text,text,jsonb,text,jsonb)','EXECUTE') THEN
        RAISE EXCEPTION 'Task 3.3B runtime append-only privilege boundary differs';
    END IF;
    IF EXISTS (
        SELECT 1 FROM pg_index i JOIN pg_class c ON c.oid=i.indexrelid
        WHERE i.indrelid='public.audit_events'::regclass
          AND pg_get_indexdef(i.indexrelid) ~* ' USING gin '
    ) THEN
        RAISE EXCEPTION 'Task 3.3B refuses an unrestricted JSON GIN index';
    END IF;
    IF (SELECT count(*) FROM public.audit_actors)<>7
       OR (SELECT count(*) FROM public.user_accounts WHERE updated_by IS NULL)<>4 THEN
        RAISE EXCEPTION 'Task 3.3B changed the protected actor state';
    END IF;
END
