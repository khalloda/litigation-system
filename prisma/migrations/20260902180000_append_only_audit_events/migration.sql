BEGIN;

-- Task 3.3B: append-only, redacted chronological events. The migration starts
-- the trail at deployment with one aggregate baseline event; it never invents
-- a historical event for an existing business row.

DO $PRECONDITION$
DECLARE
    actor_rows bigint;
    null_updates bigint;
BEGIN
    IF session_user IS DISTINCT FROM current_user
       OR NOT coalesce((SELECT rolsuper FROM pg_roles WHERE rolname=session_user),false) THEN
        RAISE EXCEPTION 'Task 3.3B requires D35 direct-superuser migration identity';
    END IF;
    IF to_regclass('public.audit_events') IS NOT NULL
       OR to_regclass('public.audit_event_table_rules') IS NOT NULL
       OR to_regclass('public.audit_event_fields') IS NOT NULL
       OR to_regclass('public.audit_event_checkpoints') IS NOT NULL THEN
        RAISE EXCEPTION 'Task 3.3B requires no pre-existing event foundation';
    END IF;
    SELECT count(*) INTO actor_rows FROM public.audit_actors;
    IF actor_rows<>7 THEN
        RAISE EXCEPTION 'Task 3.3B expected the exact seven-actor registry, found %',actor_rows;
    END IF;
    SELECT count(*) FILTER(WHERE updated_by IS NULL)
      INTO null_updates FROM public.user_accounts;
    -- The complete 38-table totals are re-proved below and permanently by
    -- db:check. This precondition catches an unaccepted Task 3.3A state before
    -- any Task 3.3B object is created.
    IF null_updates<>4 THEN
        RAISE EXCEPTION 'Task 3.3B expected exactly four historical unknown update actors';
    END IF;
    IF NOT (
        ((SELECT count(*) FROM public.invoices)=543
         AND (SELECT count(*) FROM public.payments)=597
         AND (SELECT count(*) FROM public.invoice_allocations)=47
         AND (SELECT count(*) FROM public.attendance)=4022)
        OR
        ((SELECT count(*) FROM public.invoices)=0
         AND (SELECT count(*) FROM public.payments)=0
         AND (SELECT count(*) FROM public.invoice_allocations)=0
         AND (SELECT count(*) FROM public.attendance)=0)
    ) THEN
        RAISE EXCEPTION 'Task 3.3B protected historical-live/clean-replay profile differs';
    END IF;
END
$PRECONDITION$;

