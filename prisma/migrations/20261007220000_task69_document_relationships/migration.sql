CREATE FUNCTION _migration.task69_document_membership_history(p_before jsonb,p_after jsonb,p_request jsonb,p_actor integer,p_request_id uuid) RETURNS boolean
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE kind text;tbl text;col text;desired jsonb;prior jsonb;next_member jsonb;old_member jsonb;event record;expected_fields text[];expected_before jsonb;expected_after jsonb;
BEGIN
 FOREACH kind IN ARRAY ARRAY['matters','people'] LOOP
  tbl:=CASE WHEN kind='matters' THEN 'document_matters' ELSE 'document_responsible_people' END;col:=CASE WHEN kind='matters' THEN 'matter_id' ELSE 'person_id' END;
  IF jsonb_typeof(p_after->kind) IS DISTINCT FROM 'array' THEN RETURN false;END IF;
  prior:=coalesce(p_before->kind,'[]');
  IF p_request->>'operation' IN('archive','restore') THEN
   IF p_after->kind IS DISTINCT FROM prior THEN RETURN false;END IF;
  ELSE
   BEGIN desired:=_migration.task69_document_desired(p_before,kind,p_request->'values',p_request->'related');EXCEPTION WHEN OTHERS THEN RETURN false;END;
   IF desired IS DISTINCT FROM _migration.task69_document_ids(p_after,kind) THEN RETURN false;END IF;
  END IF;
  IF EXISTS(SELECT 1 FROM jsonb_array_elements(prior) old WHERE NOT EXISTS(SELECT 1 FROM jsonb_array_elements(p_after->kind) n WHERE n->'id'=old->'id')) THEN RETURN false;END IF;
  FOR next_member IN SELECT value FROM jsonb_array_elements(p_after->kind) LOOP
   SELECT old INTO old_member FROM jsonb_array_elements(prior) old WHERE old->'id'=next_member->'id';
   IF next_member->'document_id' IS DISTINCT FROM p_after->'id' OR (old_member IS NOT NULL AND next_member-ARRAY['position','is_retired'] IS DISTINCT FROM old_member-ARRAY['position','is_retired']) THEN RETURN false;END IF;
   IF next_member IS DISTINCT FROM old_member THEN
    SELECT array_agg(f.field_name ORDER BY f.field_name),CASE WHEN old_member IS NULL THEN '{}'::jsonb ELSE coalesce(jsonb_object_agg(f.field_name,public.audit_bound_json_value(old_member->f.field_name,f.max_text_characters,f.capture_mode)),'{}') END,
     coalesce(jsonb_object_agg(f.field_name,public.audit_bound_json_value(next_member->f.field_name,f.max_text_characters,f.capture_mode)),'{}') INTO expected_fields,expected_before,expected_after
     FROM public.audit_event_fields f WHERE f.entity_schema='public' AND f.entity_table=tbl AND f.capture_mode IN('value','redacted') AND (old_member IS NULL OR old_member->f.field_name IS DISTINCT FROM next_member->f.field_name);
    IF (SELECT count(*) FROM public.audit_events e WHERE e.entity_schema='public' AND e.entity_table=tbl AND e.entity_key=jsonb_build_object('id',next_member->'id')
     AND e.actor_id=p_actor AND e.request_id=p_request_id AND e.outcome='succeeded' AND e.actor_role_snapshot IN('Administrator','Litigation Assistant')
     AND e.action=CASE WHEN old_member IS NULL THEN 'record_created' ELSE 'record_updated' END AND e.changed_fields=expected_fields AND e.before_values=expected_before AND e.after_values=expected_after)<>1 THEN RETURN false;END IF;
   END IF;
  END LOOP;
 END LOOP;
 RETURN true;
END $$;

CREATE OR REPLACE FUNCTION _migration.tasks46_47_receipt_valid(
 p_gateway text,p_actor integer,p_request jsonb,p_entity integer,p_result bigint
) RETURNS boolean LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE r record; owner record; op text;
BEGIN
 BEGIN SELECT * INTO r FROM _migration.tasks46_47_request_identity(p_request);
 EXCEPTION WHEN OTHERS THEN RETURN false; END;
 op:=r.operation;
 SELECT * INTO owner FROM _migration.tasks46_47_submission_owner WHERE submission_id=r.submission;
 IF NOT FOUND OR owner.actor_id<>p_actor OR owner.gateway<>p_gateway OR owner.operation<>op
  OR owner.entity_id<>p_entity OR owner.result_version<>p_result
  OR owner.request_payload IS DISTINCT FROM p_request THEN RETURN false; END IF;
 IF (op='create') IS DISTINCT FROM (r.identity IS NULL) OR
  (op='create' AND (p_request->'version'<>'null' OR p_result<>1)) OR
  (op<>'create' AND (r.identity<>p_entity OR r.expected<>p_result-1)) THEN RETURN false; END IF;
 IF p_gateway='documents' THEN
  IF op NOT IN('create','update','archive','restore')
   OR (op IN('create','update') AND (_migration.task69_document_related_valid(p_request->'related') IS NOT TRUE OR p_request->'facts'<>'null'))
   OR (op IN('archive','restore') AND (p_request->'values'<>'{}' OR p_request->'related'<>'null'
    OR jsonb_typeof(p_request->'facts')<>'object')) THEN RETURN false; END IF;
 ELSIF p_gateway='fee_letters' THEN
  IF op NOT IN('create','update','archive','restore','covered-add','covered-retire','covered-restore') THEN RETURN false; END IF;
  IF op IN('create','update') AND (p_request->'related'<>'null' OR p_request->'facts'<>'null') THEN RETURN false; END IF;
  IF op IN('archive','restore') AND (p_request->'values'<>'{}' OR p_request->'related'<>'null'
   OR jsonb_typeof(p_request->'facts')<>'object') THEN RETURN false; END IF;
  IF op LIKE 'covered-%' AND (p_request->'values'<>'{}' OR p_request->'facts'<>'null'
   OR jsonb_typeof(p_request->'related')<>'object'
   OR NOT p_request->'related' ?& ARRAY['membershipId','matterId']
   OR EXISTS(SELECT 1 FROM jsonb_object_keys(p_request->'related') k WHERE k NOT IN('membershipId','matterId')))
   THEN RETURN false; END IF;
 ELSIF p_gateway='matter_fee_references' THEN
  IF op NOT IN('set','clear','replace') OR p_request->'values'<>'{}' OR p_request->'facts'<>'null'
   OR jsonb_typeof(p_request->'related')<>'object'
   OR NOT p_request->'related' ?& ARRAY['oldFeeLetterId','newFeeLetterId']
   OR EXISTS(SELECT 1 FROM jsonb_object_keys(p_request->'related') k WHERE k NOT IN('oldFeeLetterId','newFeeLetterId'))
   THEN RETURN false; END IF;
 ELSE RETURN false;
 END IF;
 RETURN true;
END;
$$;
CREATE OR REPLACE FUNCTION _migration.document_edit_current_valid(p_id integer) RETURNS boolean
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE expected jsonb:=_migration.document_edit_initial_aggregate(p_id); c record; s record; v bigint; op text; patch jsonb; prior_state jsonb; next_state jsonb; boundary_version bigint;
BEGIN
 expected:=_migration.task69_document_at_relationship_boundary(expected);
 SELECT version INTO boundary_version FROM _migration.task69_document_relationship_boundary WHERE document_id=p_id;
 v:=CASE WHEN expected IS NULL THEN 1 ELSE 2 END;
 FOR c IN SELECT * FROM _migration.document_edit_change WHERE document_id=p_id ORDER BY version LOOP
  prior_state:=_migration.task69_document_at_relationship_boundary(c.before_values);
  next_state:=_migration.task69_document_at_relationship_boundary(c.after_values);
  SELECT * INTO s FROM _migration.document_edit_submission WHERE document_id=p_id AND result_version=c.version;
	  IF NOT FOUND OR s.actor_id<>c.actor_id OR c.version<>v OR prior_state IS DISTINCT FROM expected
	   OR NOT _migration.tasks46_47_receipt_valid('documents',s.actor_id,s.request_payload,p_id,c.version)
	   OR s.submission_id::text<>s.request_payload->>'submission'
	   OR (next_state->>'id')::integer<>p_id OR (next_state->>'row_version')::bigint<>v
   OR NOT EXISTS(SELECT 1 FROM public.audit_events e WHERE e.entity_schema='public'
    AND e.entity_table='documents' AND e.entity_key=jsonb_build_object('id',p_id)
    AND e.actor_id=c.actor_id AND e.request_id=c.request_id AND e.outcome='succeeded'
	    AND e.after_values->>'row_version'=v::text) THEN RETURN false; END IF;
	  op:=s.request_payload->>'operation';
	  IF op IN('create','update') THEN
	   BEGIN patch:=_migration.document_edit_values(s.request_payload->'values',prior_state,op='create');
	   EXCEPTION WHEN OTHERS THEN RETURN false; END;
     IF c.version>coalesce(boundary_version,0) THEN
      patch:=patch||jsonb_build_object('matter_id',CASE WHEN jsonb_array_length(_migration.task69_document_desired(prior_state,'matters',s.request_payload->'values',s.request_payload->'related'))=1 THEN _migration.task69_document_desired(prior_state,'matters',s.request_payload->'values',s.request_payload->'related')->0 ELSE 'null'::jsonb END,
       'responsible_person_id',CASE WHEN jsonb_array_length(_migration.task69_document_desired(prior_state,'people',s.request_payload->'values',s.request_payload->'related'))=1 THEN _migration.task69_document_desired(prior_state,'people',s.request_payload->'values',s.request_payload->'related')->0 ELSE 'null'::jsonb END);
     END IF;
	   IF op='create' THEN
	    IF prior_state IS NOT NULL OR NOT next_state @> patch THEN RETURN false; END IF;
	   ELSIF next_state-ARRAY['row_version','updated_at','updated_by','matters','people']
	    IS DISTINCT FROM (prior_state||patch)-ARRAY['row_version','updated_at','updated_by','matters','people'] THEN RETURN false; END IF;
	  ELSIF prior_state IS NULL OR next_state-ARRAY['row_version','updated_at','updated_by','is_archived','matters','people']
	   IS DISTINCT FROM prior_state-ARRAY['row_version','updated_at','updated_by','is_archived','matters','people']
	   OR (next_state->>'is_archived')::boolean IS DISTINCT FROM (op='archive') THEN RETURN false;
	  END IF;
  IF c.version>coalesce(boundary_version,0) AND _migration.task69_document_membership_history(prior_state,next_state,s.request_payload,c.actor_id,c.request_id) IS NOT TRUE THEN RETURN false;END IF;
  expected:=next_state; v:=v+1;
 END LOOP;
	 IF EXISTS(SELECT 1 FROM _migration.document_edit_submission sr WHERE sr.document_id=p_id
	  AND NOT EXISTS(SELECT 1 FROM _migration.document_edit_change ch WHERE ch.document_id=sr.document_id AND ch.version=sr.result_version AND ch.actor_id=sr.actor_id)) THEN RETURN false; END IF;
	 RETURN expected IS NOT NULL AND expected IS NOT DISTINCT FROM _migration.document_edit_aggregate(p_id) AND _migration.task69_document_compatibility(p_id);
END;
$$;
