$$;

CREATE OR REPLACE FUNCTION public.document_edit_save(p_account integer,p_session integer,p_role text,p_expires timestamptz,p_request jsonb) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public SET TimeZone='UTC' AS $$
DECLARE actor integer; r record; receipt _migration.document_edit_submission%ROWTYPE; owner _migration.tasks46_47_submission_owner%ROWTYPE; original jsonb;
 before_state jsonb; after_state jsonb; patch jsonb; columns text; selections text; assignments text;
 op text; creating boolean; lifecycle boolean; old_matter integer; new_matter integer; old_client integer;
 new_client integer; old_person integer; new_person integer; v bigint; request_id uuid; before_aggregate jsonb; old_matters jsonb; desired_matters jsonb; old_people jsonb; desired_people jsonb; members_changed boolean; member integer;
BEGIN
 PERFORM 1 FROM _migration.staff_roster_mutex WHERE singleton FOR UPDATE;
 actor:=_migration.tasks46_47_require_account(p_account,p_session,p_role,p_expires,false);
 IF actor IS DISTINCT FROM public.audit_current_actor_id() THEN RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Document actor differs from trusted context'; END IF;
 SELECT * INTO r FROM _migration.tasks46_47_request_identity(p_request);
 op:=r.operation; creating:=op='create'; lifecycle:=op IN('archive','restore');
 IF op NOT IN('create','update','archive','restore') OR creating<>(r.identity IS NULL)
  OR (lifecycle AND p_role<>'Administrator') THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Invalid document operation'; END IF;
	 PERFORM pg_advisory_xact_lock(hashtextextended(r.submission::text,4647));
	 SELECT * INTO owner FROM _migration.tasks46_47_submission_owner WHERE submission_id=r.submission;
	 IF FOUND AND (owner.actor_id<>actor OR owner.gateway<>'documents' OR owner.operation<>op OR owner.request_payload IS DISTINCT FROM p_request) THEN
	  RAISE EXCEPTION USING ERRCODE=CASE WHEN owner.actor_id<>actor THEN '42501' ELSE '22023' END,MESSAGE='submission payload differs across gateway, actor, or payload';
	 END IF;
	 SELECT * INTO receipt FROM _migration.document_edit_submission WHERE submission_id=r.submission;
	 IF FOUND THEN
	  IF owner.submission_id IS NULL THEN RAISE EXCEPTION 'Document receipt has no global submission owner'; END IF;
  IF receipt.actor_id<>actor THEN RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Document submission belongs to another actor'; END IF;
  IF receipt.request_payload IS DISTINCT FROM p_request THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Document submission payload differs'; END IF;
  RETURN jsonb_build_object('id',receipt.document_id,'version',receipt.result_version::text,'changed',true);
 END IF;
 IF NOT creating THEN
  SELECT to_jsonb(d) INTO original FROM public.documents d WHERE id=r.identity;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Document not found'; END IF;
 END IF;
 IF lifecycle THEN
  IF p_request->'values'<>'{}' OR p_request->'related'<>'null' OR p_request->'facts' IS DISTINCT FROM _migration.document_edit_facts(r.identity) THEN RAISE EXCEPTION USING ERRCODE='40001',MESSAGE='Document version or confirmation is stale'; END IF;
  patch:=jsonb_build_object('is_archived',op='archive');
 ELSE
  IF p_request->'facts'<>'null' THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Document edit cannot contain lifecycle facts'; END IF;
  patch:=_migration.document_edit_values(p_request->'values',original,creating);
 END IF;
 before_aggregate:=_migration.document_edit_aggregate(r.identity);
 old_matters:=_migration.task69_document_ids(before_aggregate,'matters');old_people:=_migration.task69_document_ids(before_aggregate,'people');
 IF lifecycle THEN desired_matters:=old_matters;desired_people:=old_people;
 ELSE
  desired_matters:=_migration.task69_document_desired(before_aggregate,'matters',p_request->'values',p_request->'related');
  desired_people:=_migration.task69_document_desired(before_aggregate,'people',p_request->'values',p_request->'related');
 END IF;
 old_client:=(original->>'client_id')::integer;new_client:=CASE WHEN patch ? 'client_id' THEN (patch->>'client_id')::integer ELSE old_client END;
 FOR member IN SELECT DISTINCT value::text::integer FROM jsonb_array_elements(old_matters||desired_matters) ORDER BY 1 LOOP
  PERFORM 1 FROM public.matters WHERE id=member AND NOT is_archived FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Restore archived document parent';END IF;
 END LOOP;
 PERFORM 1 FROM public.clients WHERE id IN(SELECT DISTINCT x FROM unnest(ARRAY[old_client,new_client]) x WHERE x IS NOT NULL) ORDER BY id FOR UPDATE;
 IF (jsonb_array_length(old_matters)=0 AND old_client IS NOT NULL AND EXISTS(SELECT 1 FROM public.clients WHERE id=old_client AND is_archived))
 OR (jsonb_array_length(desired_matters)=0 AND new_client IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.clients WHERE id=new_client AND NOT is_archived))
 OR (patch ? 'client_id' AND new_client IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.clients WHERE id=new_client AND NOT is_archived)) THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Restore archived document client';END IF;
 FOR member IN SELECT DISTINCT value::text::integer FROM jsonb_array_elements(old_people||desired_people) ORDER BY 1 LOOP
  PERFORM 1 FROM public.people WHERE id=member FOR UPDATE;
  IF NOT FOUND OR (desired_people @> jsonb_build_array(member) AND NOT old_people @> jsonb_build_array(member) AND NOT EXISTS(SELECT 1 FROM public.people WHERE id=member AND is_active AND is_staff)) THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Active staff person required';END IF;
 END LOOP;
 members_changed:=desired_matters IS DISTINCT FROM old_matters OR desired_people IS DISTINCT FROM old_people;
 IF NOT lifecycle THEN
  new_matter:=CASE WHEN jsonb_array_length(desired_matters)=1 THEN (desired_matters->>0)::integer ELSE NULL END;
  new_person:=CASE WHEN jsonb_array_length(desired_people)=1 THEN (desired_people->>0)::integer ELSE NULL END;
  IF creating OR coalesce(to_jsonb(new_matter),'null'::jsonb) IS DISTINCT FROM original->'matter_id' THEN patch:=patch||jsonb_build_object('matter_id',new_matter);END IF;
  IF creating OR coalesce(to_jsonb(new_person),'null'::jsonb) IS DISTINCT FROM original->'responsible_person_id' THEN patch:=patch||jsonb_build_object('responsible_person_id',new_person);END IF;
 END IF;
 IF NOT creating THEN
  SELECT to_jsonb(d) INTO original FROM public.documents d WHERE id=r.identity FOR UPDATE;
  IF (original->>'row_version')::bigint<>r.expected THEN RAISE EXCEPTION USING ERRCODE='40001',MESSAGE='Document version or confirmation is stale'; END IF;
  IF NOT lifecycle AND (original->>'is_archived')::boolean THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Restore archived document before editing'; END IF;
  before_state:=_migration.document_edit_aggregate(r.identity);
 END IF;
 PERFORM _migration.tasks46_47_require_account(p_account,p_session,p_role,p_expires,lifecycle);
 IF NOT creating AND ((lifecycle AND (original->>'is_archived')::boolean=(op='archive')) OR (NOT lifecycle AND patch='{}' AND NOT members_changed)) THEN
  RETURN jsonb_build_object('id',r.identity,'version',r.expected::text,'changed',false);
 END IF;
 PERFORM public.audit_ensure_event_context(); PERFORM set_config('litigation.tasks46_47_gateway','on',true);
 IF creating THEN
  SELECT string_agg(format('%I',key),',' ORDER BY key),string_agg(format('v.%I',key),',' ORDER BY key)
   INTO columns,selections FROM jsonb_object_keys(patch) key;
  EXECUTE format('INSERT INTO public.documents(%s,updated_at) SELECT %s,statement_timestamp() FROM jsonb_populate_record(NULL::public.documents,$1) v RETURNING id',columns,selections) INTO r.identity USING patch;
 ELSE
  SELECT string_agg(format('%I=v.%I',key,key),',' ORDER BY key) INTO assignments FROM jsonb_object_keys(patch) key;
  EXECUTE format('UPDATE public.documents d SET %srow_version=d.row_version+1 FROM jsonb_populate_record(NULL::public.documents,$1) v WHERE d.id=$2',CASE WHEN assignments IS NULL THEN '' ELSE assignments||',' END) USING original||patch,r.identity;
 END IF;
 IF NOT lifecycle THEN
  PERFORM _migration.task69_document_assign(r.identity,'matters',desired_matters);
  PERFORM _migration.task69_document_assign(r.identity,'people',desired_people);
 END IF;
 IF lifecycle THEN PERFORM public.audit_append_semantic_event(op,'succeeded','public','documents',jsonb_build_object('id',r.identity),NULL,NULL,NULL,'{}',NULL,'{}'); END IF;
 SELECT row_version INTO v FROM public.documents WHERE id=r.identity; after_state:=_migration.document_edit_aggregate(r.identity);
 request_id:=current_setting('litigation.audit_request_id')::uuid;
 INSERT INTO _migration.document_edit_change VALUES(r.identity,v,actor,before_state,after_state,request_id);
	 INSERT INTO _migration.tasks46_47_submission_owner(submission_id,actor_id,gateway,operation,entity_id,request_payload,result_version) VALUES(r.submission,actor,'documents',op,r.identity,p_request,v);
	 INSERT INTO _migration.document_edit_submission(submission_id,actor_id,request_payload,document_id,result_version) VALUES(r.submission,actor,p_request,r.identity,v);
 RETURN jsonb_build_object('id',r.identity,'version',v::text,'changed',true);
END;
$$;

DO $$ DECLARE routine regprocedure;BEGIN
 FOR routine IN SELECT p.oid::regprocedure FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='_migration' AND p.proname LIKE 'task69_document_%' LOOP EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC,litigation_runtime',routine);END LOOP;
 IF EXISTS(SELECT 1 FROM public.documents WHERE _migration.document_edit_current_valid(id) IS NOT TRUE) THEN RAISE EXCEPTION 'Document relationship boundary changed original state';END IF;
END $$;
CREATE OR REPLACE FUNCTION _migration.audit_history_parent(p_table text,p_id text,p_field text) RETURNS text
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE result text;
BEGIN
 IF p_id !~ '^[1-9][0-9]{0,9}$' OR p_id::numeric>2147483647 THEN RETURN NULL; END IF;
 IF (p_table,p_field) NOT IN (('document_matters','document_id'),('document_matters','matter_id'),('document_responsible_people','document_id'),('document_responsible_people','person_id'),('contacts','client_id'),('client_logos','client_id'),
  ('matter_lawyers','matter_id'),('matter_parties','matter_id'),('matter_party_roles','party_id'),
  ('hearing_attendees','hearing_id'),('task_actions','task_id'),('admin_task_assignees','task_id'),('admin_task_assignees','person_id'),('power_of_attorney_lawyers','power_of_attorney_id'),
  ('fee_letter_matters','fee_letter_id'),('fee_letter_matters','matter_id'),
  ('matter_fee_letter_references','matter_id'),('matter_fee_letter_references','fee_letter_id'),
  ('invoice_allocations','invoice_id'),('payments','invoice_id'),('person_name_alias','person_id'),('user_accounts','person_id')) THEN RETURN NULL; END IF;
 EXECUTE format('SELECT %I::text FROM public.%I WHERE id=$1',p_field,p_table) INTO result USING p_id::integer;
 RETURN result;
END;
$$;
CREATE OR REPLACE FUNCTION _migration.audit_history_in_scope(e public.audit_events,p_table text,p_id text) RETURNS boolean
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE field text; party text;
BEGIN
 IF p_table IS NULL THEN RETURN true; END IF;
 IF e.entity_schema='public' AND e.entity_table=p_table AND e.entity_key->>'id'=p_id THEN RETURN true; END IF;
 field:=CASE
  WHEN p_table='documents' AND e.entity_table IN('document_matters','document_responsible_people') THEN 'document_id'
  WHEN p_table='clients' AND e.entity_table IN('contacts','client_logos') THEN 'client_id'
  WHEN p_table='matters' AND e.entity_table IN('document_matters','matter_lawyers','matter_parties','matter_fee_letter_references','fee_letter_matters') THEN 'matter_id'
  WHEN p_table='hearings' AND e.entity_table='hearing_attendees' THEN 'hearing_id'
  WHEN p_table='admin_tasks' AND e.entity_table IN('task_actions','admin_task_assignees') THEN 'task_id'
  WHEN p_table='powers_of_attorney' AND e.entity_table='power_of_attorney_lawyers' THEN 'power_of_attorney_id'
  WHEN p_table='fee_letters' AND e.entity_table IN('fee_letter_matters','matter_fee_letter_references') THEN 'fee_letter_id'
  WHEN p_table='invoices' AND e.entity_table IN('invoice_allocations','payments') THEN 'invoice_id'
  WHEN p_table='people' AND e.entity_table IN('document_responsible_people','person_name_alias','user_accounts','admin_task_assignees') THEN 'person_id'
  WHEN p_table='matter_parties' AND e.entity_table='matter_party_roles' THEN 'party_id' END;
 IF field IS NOT NULL THEN RETURN p_id=ANY(_migration.audit_history_association(e,field)); END IF;
 IF p_table='matters' AND e.entity_table='matter_party_roles' THEN
  FOREACH party IN ARRAY _migration.audit_history_association(e,'party_id') LOOP
   IF _migration.audit_history_parent('matter_parties',party,'matter_id')=p_id
    OR EXISTS(SELECT 1 FROM public.audit_events h WHERE h.entity_table='matter_parties' AND h.entity_key->>'id'=party
      AND (h.before_values->>'matter_id'=p_id OR h.after_values->>'matter_id'=p_id)) THEN RETURN true; END IF;
  END LOOP;
 END IF;
 RETURN false;
END;
$$;
CREATE OR REPLACE FUNCTION _migration.matter_lifecycle_counts(p_id integer) RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,public AS $$
 SELECT jsonb_build_object(
 'hearings',(SELECT count(*) FROM public.hearings WHERE matter_id=p_id),
 'tasks',(SELECT count(*) FROM public.admin_tasks WHERE matter_id=p_id),
 'steps',(SELECT count(*) FROM public.task_actions a JOIN public.admin_tasks t ON t.id=a.task_id WHERE t.matter_id=p_id),
 'documents',(SELECT count(*) FROM public.document_matters WHERE matter_id=p_id AND NOT is_retired),
 'feeLetters',(SELECT count(DISTINCT fee_letter_id) FROM (SELECT fee_letter_id FROM public.fee_letter_matters WHERE matter_id=p_id UNION SELECT fee_letter_id FROM public.matter_fee_letter_references WHERE matter_id=p_id) f),
 'parties',(SELECT count(*) FROM public.matter_parties WHERE matter_id=p_id AND NOT is_retired),
 'capacities',(SELECT count(*) FROM public.matter_party_roles r JOIN public.matter_parties p ON p.id=r.party_id WHERE p.matter_id=p_id AND NOT p.is_retired AND NOT r.is_retired),
 'lawyers',(SELECT count(*) FROM public.matter_lawyers WHERE matter_id=p_id AND NOT is_retired))
$$;
COMMIT;
