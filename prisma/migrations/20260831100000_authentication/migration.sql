DECLARE
  problems integer;
BEGIN
  SELECT count(*) INTO problems FROM (
    VALUES
      ('KHelmy'::text, 'خالد حلمي'::text, 'khelmy@sarieldin.com'::text, 'Administrator'::text, true),
      ('MHussien'::text, 'محمد حسين'::text, 'mhussien@sarieldin.com'::text, 'Litigation Assistant'::text, true),
      ('IHamdy'::text, 'إيهاب حمدي'::text, 'ihamdy@sarieldin.com'::text, 'Lawyer'::text, false),
      ('SKhattab'::text, 'سامي إبراهيم خطاب'::text, 'skhattab@sarieldin.com'::text, 'Paralegal'::text, false)
  ) expected(username, name_ar, email, role_code, native)
  LEFT JOIN public.user_accounts u ON u.username = expected.username
  LEFT JOIN public.people p ON p.id = u.person_id
  WHERE u.id IS NULL
     OR p.name_ar IS DISTINCT FROM expected.name_ar
     OR p.email IS DISTINCT FROM expected.email
     OR u.role_code IS DISTINCT FROM expected.role_code
     OR p.is_application_native IS DISTINCT FROM expected.native
     OR p.can_login IS NOT TRUE
     OR u.password_hash IS NOT NULL;

  IF problems <> 0 OR (SELECT count(*) FROM public.user_accounts) <> 4 THEN
    RAISE EXCEPTION 'Task 3.1 account mapping postcondition failed';
  END IF;
  IF (SELECT count(*) FROM public.people WHERE NOT is_application_native) <> 135
     OR (SELECT count(*) FROM public.people WHERE is_application_native) <> 2
     OR (SELECT count(*) FROM public.person_name_alias) <> 350 THEN
    RAISE EXCEPTION 'Task 3.1 protected/native roster postcondition failed';
  END IF;
END;
$$;
